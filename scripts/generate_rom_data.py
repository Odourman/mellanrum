#!/usr/bin/env python3
"""Convert V5.1 canonical room geometry and GRAPHICS V5.1 sprites/PF CSV into DASM bytes.
Usage: python scripts/generate_rom_data.py --original path/to/rooms.json --graphics path/to/graphics --output rom/src/data.inc
Use --check with the same args to validate an existing generated file without writing it.
All input files stay untouched; their SHA-256 goes into a separate manifest.
"""
import argparse, csv, hashlib, json, pathlib, sys

def rev4(v): return int(f'{v:04b}'[::-1], 2)
def pfpack(bits):
    assert len(bits)==20 and set(bits)<={'0','1'}
    words=[int(bits[i:i+4],2) for i in range(0,20,4)]
    return [rev4(words[0])<<4,(words[1]<<4)|words[2],rev4(words[3])|(rev4(words[4])<<4)]

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--original',required=True);ap.add_argument('--graphics',required=True);ap.add_argument('--output',required=True);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    rooms=json.loads(pathlib.Path(args.original).read_text());g=pathlib.Path(args.graphics)
    masks=json.loads((g/'03_SPRITES_BITMATRISER/sprite_masks.json').read_text())['sprites']
    assert len(rooms)==15 and len(masks)==25
    assert [r['id'] for r in rooms]==[f'{a}-{n:02d}' for a in ('I','II','III') for n in range(1,6)]
    assert all(rooms[k]['half_rows']==rooms[k+5]['half_rows']==rooms[k+10]['half_rows'] for k in range(5))
    assert all(len(r['half_rows'])==8 and all(len(row)==5 for row in r['half_rows']) for r in rooms)
    out=['; AUTOGENERATED by scripts/generate_rom_data.py. DO NOT EDIT.','; EXACT source geometry: V5.1 rooms.json; PF and bitmaps: GRAPHICS V5.1.', '; The mask atlas contains exactly 25 8x8 images; selected P0/P1 masks follow.']
    def byte(name, vals, width=16):
        assert all(0<=v<=255 for v in vals),(name,vals)
        out.append(f'{name}:')
        for i in range(0,len(vals),width):out.append('        dc.b '+','.join(f'${v:02X}' for v in vals[i:i+width]))
    def labeladdr(name,labels):
        out.append(name+'Lo:');out.append('        dc.b '+','.join('<'+l for l in labels))
        out.append(name+'Hi:');out.append('        dc.b '+','.join('>'+l for l in labels))
    byte('DeltaX',[1,0,255,0]);byte('DeltaY',[0,1,0,255]);byte('TurnOffset',[0,1,3,2]);byte('BitMask',[1,2,4,8,16])
    byte('GroupBase',[5*i for i in range(8)]);byte('PFBase',[6*i for i in range(8)])
    byte('UpperPFOffset',[0,1,1,2,2]);byte('LowerPFOffset',[3,4,4,5,5])
    byte('UpperToggle',[0x50,0xA0,0x0A,0x05,0x50]);byte('LowerToggle',[0x60,0x60,0x06,0x06,0x60])
    byte('SpriteRowIndex',[8,8,8,8,0,1,2,3,4,5,6,7,8,8]);byte('PresenceHUD',[0,4,10,1])
    byte('PaletteBG',[0xA0,0xA0,0xF0,0x0C,0x80]);byte('PalettePF',[0xB6,0xB6,0xE6,0x84,0x0C])
    byte('PaletteOwl',[0x0E,0x0E,0x0C,0x00,0x0E]);byte('PaletteCursor',[0x26,0x26,0x36,0x46,0x4A])
    byte('SoundControl0',[8,8,6,10]);byte('SoundControl1',[6,6,12,4]);byte('SoundPitch0',[15,12,15,13]);byte('SoundPitch1',[21,22,26,28])
    for field,name in [('act','RoomAct'),('stone_initial','RoomPolarity')]:byte(name,[r[field] for r in rooms])
    for n,field,elem in [('RoomOwlX','owl_start',0),('RoomOwlY','owl_start',1),('RoomOwlDir','owl_start',2),('RoomStoneX','stone',0),('RoomStoneY','stone',1),('RoomExitX','exit',0),('RoomExitY','exit',1)]:byte(n,[r[field][elem] for r in rooms])
    byte('RoomGeom',[i%5 for i in range(15)]);
    byte('RoomWarning',[255]*9+[4,4,2,1,0,2]);byte('RoomActive',[255]*12+[2,1,3]);
    for geom in range(5):
        r=rooms[geom]
        mut=[sum(1<<x for x,c in enumerate(row) if c in 'Tt') for row in r['half_rows']]
        blocked=[sum(1<<x for x,c in enumerate(row) if c in '#T') for row in r['half_rows']]
        byte(f'GeoMap{geom}',mut+blocked)
        pf=[]
        p=g/'06_ALLA_15_RUM'/r['id']/(r['id']+'_PF0_PF1_PF2_AT_START.csv')
        with p.open() as f:
            rows=list(csv.DictReader(f))
        assert len(rows)==16
        for y in range(8):
            for band in range(2):
                entry=rows[y*2+band]
                bits=entry['visible_half_bits']
                packed=pfpack(bits)
                asserted=[int(entry[f'pf{i}'].replace('$',''),16) for i in range(3)]
                assert packed==asserted,(r['id'],y,band,packed,asserted)
                pf.extend(packed)
        byte(f'GeoPF{geom}',pf)
    labeladdr('GeoMap',[f'GeoMap{i}' for i in range(5)])
    labeladdr('GeoPF',[f'GeoPF{i}' for i in range(5)])
    # Source order is TOP -> BOTTOM. Raster sprite table uses reverse index 7..0.
    selected=['OWL_E_IDLE','CURSOR_IDLE','CURSOR_ACK','CURSOR_DENIED','CURSOR_INTERCEPT']
    byte('BlankSprite',[0]*9)
    for key,label in zip(selected,['OwlSprite','CursorIdle','CursorAck','CursorDenied','CursorIntercept']):
        arr=[int(s.replace('$',''),16) for s in masks[key]['rows_hex']]
        assert len(arr)==8 and all(0<=x<=255 for x in arr)
        byte(label,list(reversed(arr))+[0])
    labeladdr('CursorSprite',['CursorIdle','CursorAck','CursorDenied','CursorIntercept'])
    font={
        'M':['101','111','111','101','101'],'E':['111','100','110','100','111'],
        'L':['100','100','100','100','111'],'A':['010','101','111','101','101'],
        'N':['101','111','111','111','101'],'R':['110','101','110','101','101'],
        'U':['101','101','101','101','111'],'K':['101','101','110','101','101'],
        'F':['111','100','110','100','100'],'I':['111','010','010','010','111'],
    }
    # One uninterrupted 9-character word across the FULL 40 PF pixels. A right-half
    # TIA PF rewrite on every glyph scanline is required; CTRLPF=0 repeats by default.
    # 3x5 source font x 9 chars + one zero spacer each + 2px left/right margin.
    word='MELLANRUM'
    left=[[],[],[]];right=[[],[],[]]
    for y in range(7):
        bits='00'+''.join((font[c][y-1] if 1<=y<=5 else '000')+'0' for c in word)+'00'
        assert len(bits)==40
        l=pfpack(bits[:20]);r=pfpack(bits[20:])
        for idx in range(3):left[idx].append(l[idx]);right[idx].append(r[idx])
    for i in range(3): byte(f'TitleLeftPF{i}',left[i]);byte(f'TitleRightPF{i}',right[i])
    # No hardware-mode UI is drawn: the console LEFT A/B switch alone selects mode.
    # A negative central notch, outlined only by transitory conifer branches.
    # Physically drawn PF OR+AND masks never enter the collision map or pfbuf.
    byte('ShadowCrownOr', [0,0,0x33,0x15,0x13,0,0,0])
    byte('ShadowCrownAnd',[0xFF,0xFF,0x3F,0x1F,0x3F,0xFF,0xFF,0xFF])
    byte('ShadowStemOr',  [0,0,0x11,0x11,0x10,0x20,0,0])
    byte('ShadowStemAnd', [0xFF,0xFF,0x1F,0x1F,0x1F,0x3F,0xFF,0xFF])
    result='\n'.join(out)+'\n'
    path=pathlib.Path(args.output)
    if args.check:
        assert path.read_text()==result, f'generated data drift: {path}'
    else:
        path.write_text(result)
    print('DATA', 'CHECK_OK' if args.check else 'WRITTEN',len(result),'chars','source room JSON SHA256',hashlib.sha256(pathlib.Path(args.original).read_bytes()).hexdigest())
if __name__=='__main__':main()
